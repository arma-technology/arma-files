package pl.arma.files

fun guessMime(name: String): String = when (name.substringAfterLast('.', "").lowercase()) {
    "txt", "log", "ini", "cfg", "conf", "kt", "kts", "java", "c", "cpp", "h", "hpp", "py", "sh" -> "text/plain"
    "md", "markdown" -> "text/markdown"
    "json" -> "application/json"
    "yaml", "yml" -> "application/yaml"
    "xml" -> "application/xml"
    "svg" -> "image/svg+xml"
    "jpg", "jpeg" -> "image/jpeg"
    "png" -> "image/png"
    "gif" -> "image/gif"
    "webp" -> "image/webp"
    "bmp" -> "image/bmp"
    "heic", "heif" -> "image/heif"
    "avif" -> "image/avif"
    // Filmy i dźwięk: wszystkie kontenery, które czyta wbudowany odtwarzacz
    // (ekstraktory media3 1.11). Czy obraz i dźwięk zagrają, zależy jeszcze od
    // dekoderów telefonu — np. AC-3/DTS albo MPEG-2 nie ma na każdym.
    "mp4", "m4v", "f4v" -> "video/mp4"
    "mov" -> "video/quicktime"
    "3gp" -> "video/3gpp"
    "3g2" -> "video/3gpp2"
    "mkv", "mk3d" -> "video/x-matroska"
    "webm" -> "video/webm"
    "avi" -> "video/x-msvideo"
    "flv" -> "video/x-flv"
    "mpg", "mpeg", "m2p", "vob" -> "video/mpeg"
    // Bez .ogv: odtwarzacz czyta z Ogg tylko dźwięk (sprawdzone na telefonie).
    // .ts zostaje TypeScriptem — nagrania MPEG-TS z kamer mają zwykle .mts/.m2ts.
    "mts", "m2ts" -> "video/mp2t"
    "mp3" -> "audio/mpeg"
    // m4a/m4b: AAC albo ALAC w kontenerze MP4 (dyktafon, iTunes, audiobooki).
    "m4a", "m4b" -> "audio/mp4"
    "3ga" -> "audio/3gpp"
    "aac", "adts" -> "audio/aac"
    "wav", "wave" -> "audio/wav"
    "flac" -> "audio/flac"
    "ogg", "oga" -> "audio/ogg"
    "opus" -> "audio/opus"
    "weba" -> "audio/webm"
    "mka" -> "audio/x-matroska"
    "amr" -> "audio/amr"
    "awb" -> "audio/amr-wb"
    "ac3" -> "audio/ac3"
    "ec3" -> "audio/eac3"
    "ac4" -> "audio/ac4"
    "pdf" -> "application/pdf"
    "zip" -> "application/zip"
    "7z" -> "application/x-7z-compressed"
    "rar" -> "application/vnd.rar"
    "tar" -> "application/x-tar"
    "gz", "tgz" -> "application/gzip"
    "bz2", "tbz", "tbz2" -> "application/x-bzip2"
    "xz", "txz" -> "application/x-xz"
    "zst", "tzst" -> "application/zstd"
    "lzma" -> "application/x-lzma"
    "jar" -> "application/java-archive"
    "html", "htm" -> "text/html"
    "css" -> "text/css"
    "js" -> "text/javascript"
    else -> "application/octet-stream"
}
