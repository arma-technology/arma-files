package pl.arma.files

fun guessMime(name: String): String = when (name.substringAfterLast('.', "").lowercase()) {
    "txt", "log", "ini", "cfg", "conf", "kt", "kts", "java", "c", "cpp", "h", "hpp", "py", "sh" -> "text/plain"
    "md", "markdown" -> "text/markdown"
    "json" -> "application/json"
    "yaml", "yml" -> "application/yaml"
    "xml" -> "application/xml"
    "svg" -> "image/svg+xml"
    "jpg", "jpeg" -> "image/jpeg"
    "png" -> "image/png"
    "gif" -> "image/gif"
    "webp" -> "image/webp"
    "bmp" -> "image/bmp"
    "heic", "heif" -> "image/heif"
    "avif" -> "image/avif"
    "mp4", "m4v" -> "video/mp4"
    "mkv" -> "video/x-matroska"
    "webm" -> "video/webm"
    "mp3" -> "audio/mpeg"
    "wav" -> "audio/wav"
    "flac" -> "audio/flac"
    "ogg" -> "audio/ogg"
    "pdf" -> "application/pdf"
    "zip" -> "application/zip"
    "7z" -> "application/x-7z-compressed"
    "rar" -> "application/vnd.rar"
    "tar" -> "application/x-tar"
    "gz", "tgz" -> "application/gzip"
    "bz2", "tbz", "tbz2" -> "application/x-bzip2"
    "xz", "txz" -> "application/x-xz"
    "zst", "tzst" -> "application/zstd"
    "lzma" -> "application/x-lzma"
    "jar" -> "application/java-archive"
    "html", "htm" -> "text/html"
    "css" -> "text/css"
    "js" -> "text/javascript"
    else -> "application/octet-stream"
}
